// Builds CSS custom properties and a typed JS module from the token sources in ../src.
// No dependencies: runs on plain Node 20+. Usage: node scripts/build.mjs
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (f) => JSON.parse(readFileSync(join(root, "src", f), "utf8"));

const primitives = read("color.primitives.json");
const semantic = read("color.semantic.json");
const sizing = read("sizing.json");
const typography = read("typography.json");

const HEX = /^#[0-9a-f]{6}$/i;
const cssName = (key) => key.replace(/\./g, "-").toLowerCase();
const errors = [];

// A colour reference is "group.step" (a primitive) with an optional "/percent" opacity.
function parseRef(ref, where) {
  const [base, pct] = String(ref).split("/");
  const alpha = pct === undefined ? 1 : Number(pct) / 100;
  if (!(base in primitives)) errors.push(`${where}: unknown primitive "${base}"`);
  if (!(alpha >= 0 && alpha <= 1)) errors.push(`${where}: bad opacity "${pct}"`);
  return { base, alpha };
}

function resolveHex(key, seen = new Set()) {
  if (seen.has(key)) throw new Error(`Alias cycle at ${key}`);
  seen.add(key);
  const v = primitives[key];
  if (v === undefined) throw new Error(`Unknown primitive ${key}`);
  return HEX.test(v) ? v.toLowerCase() : resolveHex(v, seen);
}

const toRgba = (hex, alpha) => {
  const n = (i) => parseInt(hex.slice(i, i + 2), 16);
  return alpha >= 1 ? hex : `rgba(${n(1)}, ${n(3)}, ${n(5)}, ${Math.round(alpha * 1000) / 1000})`;
};

// ---- validate ----
for (const [k, v] of Object.entries(primitives)) {
  if (!HEX.test(v) && !(v in primitives)) errors.push(`primitive ${k}: "${v}" is neither a hex colour nor a primitive`);
}
for (const [k, v] of Object.entries(semantic)) {
  for (const mode of ["light", "dark"]) {
    if (!v[mode]) errors.push(`semantic ${k}: missing ${mode} value`);
    else parseRef(v[mode], `semantic ${k} (${mode})`);
  }
}
if (errors.length) {
  console.error("Token validation failed:\n - " + errors.join("\n - "));
  process.exit(1);
}

// ---- CSS ----
const cssValue = (ref) => {
  const { base, alpha } = parseRef(ref, "");
  const v = `var(--color-${cssName(base)})`;
  if (alpha >= 1) return v;
  return `color-mix(in srgb, ${v} ${Math.round(alpha * 100)}%, transparent)`;
};
const semanticBlock = (mode) =>
  Object.entries(semantic)
    .map(([k, v]) => `  --color-${cssName(k)}: ${cssValue(v[mode])};`)
    .join("\n");

const primitiveVars = Object.entries(primitives).map(([k, v]) => {
  const value = HEX.test(v) ? v.toLowerCase() : `var(--color-${cssName(v)})`;
  return `  --color-${cssName(k)}: ${value};`;
});
const sizeVars = Object.entries(sizing).map(([k, v]) => `  --size-${cssName(k)}: ${v}px;`);
const familyVars = Object.entries(typography.fontFamily).map(
  ([k, v]) => `  --font-family-${cssName(k)}: "${v}", system-ui, -apple-system, "Segoe UI", sans-serif;`
);
const weightVars = Object.entries(typography.fontWeight).map(([k, v]) => `  --font-weight-${cssName(k)}: ${v};`);
const fontSizeVars = Object.entries(typography.fontSize).map(([k, v]) => `  --font-size-${cssName(k)}: ${v}px;`);

const css = `/* GENERATED by scripts/build.mjs from packages/tokens/src. Do not edit by hand. */

/* Primitives, sizing and typography (theme independent) */
:root {
${[...primitiveVars, ...sizeVars, ...familyVars, ...weightVars, ...fontSizeVars].join("\n")}
}

/* Semantic colours: light is the default */
:root,
[data-theme="light"] {
  color-scheme: light;
${semanticBlock("light")}
}

/* Semantic colours: dark, chosen explicitly */
[data-theme="dark"] {
  color-scheme: dark;
${semanticBlock("dark")}
}

/* Semantic colours: dark, following the OS unless a theme is set explicitly */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]):not([data-theme="dark"]) {
    color-scheme: dark;
${semanticBlock("dark")
  .split("\n")
  .map((l) => "  " + l)
  .join("\n")}
  }
}
`;

// ---- JS module (resolved values, for docs pages and tooling) ----
const resolved = (mode) =>
  Object.fromEntries(
    Object.entries(semantic).map(([k, v]) => {
      const { base, alpha } = parseRef(v[mode], k);
      return [k, toRgba(resolveHex(base), alpha)];
    })
  );
const tokens = {
  color: {
    primitives: Object.fromEntries(Object.keys(primitives).map((k) => [k, resolveHex(k)])),
    light: resolved("light"),
    dark: resolved("dark"),
  },
  size: sizing,
  font: { family: typography.fontFamily, weight: typography.fontWeight, size: typography.fontSize },
};

const js = `// GENERATED by scripts/build.mjs. Do not edit by hand.
export const tokens = ${JSON.stringify(tokens, null, 2)};
export default tokens;
`;
const dts = `// GENERATED by scripts/build.mjs. Do not edit by hand.
export interface Tokens {
  color: {
    primitives: Record<string, string>;
    light: Record<string, string>;
    dark: Record<string, string>;
  };
  size: Record<string, number>;
  font: {
    family: Record<string, string>;
    weight: Record<string, number>;
    size: Record<string, number>;
  };
}
export declare const tokens: Tokens;
export default tokens;
`;

mkdirSync(join(root, "dist"), { recursive: true });
writeFileSync(join(root, "dist", "tokens.css"), css);
writeFileSync(join(root, "dist", "index.js"), js);
writeFileSync(join(root, "dist", "index.d.ts"), dts);
console.log(
  `tokens built: ${Object.keys(primitives).length} primitives, ${Object.keys(semantic).length} semantic (light + dark), ` +
    `${Object.keys(sizing).length} sizes, ${Object.keys(typography.fontSize).length} font sizes`
);
